#!/usr/bin/env python3
"""Generate rust/jni/src/jni_sys.rs from a vendored, unmodified jni.h.

The layout of JNINativeInterface_ is a strict ABI contract: every entry must
appear in the exact order declared by jni.h.  Hand-writing that order is
error-prone, so we derive it mechanically from the header and emit one
`*mut c_void` field per entry.  Call sites transmute the field they need to the
correct function-pointer type (see jni_sys.rs::api functions).

Usage: python3 rust/tools/gen_jni_sys.py rust/tools/jni.h rust/jni/src/jni_sys.rs
"""
import re
import sys

def main(src: str, dst: str) -> None:
    text = open(src, "r", encoding="utf-8", errors="replace").read()

    start = text.index("struct JNINativeInterface_ {")
    body = text[start:]
    body = body[body.index("{") + 1:]
    end = body.index("\n};")
    body = body[:end]

    # Every field is either `void *reservedN;` or `<ret> (JNICALL *Name)(args...)`.
    # Collect them in declaration order.
    fields = []
    for m in re.finditer(r"\(\s*JNICALL\s*\*\s*(\w+)\s*\)", body):
        fields.append((m.start(), m.group(1)))
    for m in re.finditer(r"void\s*\*\s*(reserved\d+)\s*;", body):
        fields.append((m.start(), m.group(1)))
    fields.sort()

    out = []
    out.append("// @generated by rust/tools/gen_jni_sys.py from rust/tools/jni.h -- DO NOT EDIT.")
    out.append("//")
    out.append("// `JNINativeInterface` is a byte-for-byte mirror of jni.h's struct of the same")
    out.append("// name.  Fields are left untyped (`*mut c_void`) on purpose: the only thing that")
    out.append("// matters for ABI compatibility is the *order* and *count* of the entries.")
    out.append("// Typed accessors live in `jni_sys.rs` next to this file.")
    out.append("")
    out.append("#![allow(non_snake_case)]")
    out.append("#![allow(dead_code)]")
    out.append("")
    out.append("use core::ffi::c_void;")
    out.append("")
    out.append("/// Mirror of C `JNINativeInterface_`.")
    out.append("#[repr(C)]")
    out.append("pub struct JNINativeInterface {")
    for _, name in fields:
        out.append("    pub %s: *mut c_void," % name)
    out.append("}")
    out.append("")
    out.append("pub const JNI_NATIVE_INTERFACE_FIELD_COUNT: usize = %d;" % len(fields))
    out.append("")
    open(dst, "w", encoding="utf-8").write("\n".join(out))
    print("wrote %s with %d fields" % (dst, len(fields)))

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
